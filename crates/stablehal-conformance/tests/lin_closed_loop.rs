//! LIN conformance closed loop (risk T10): the reference schedule-table
//! publisher must pass every standard case, and the suite's declared
//! `probes` must cover every clause `LinContract` enforces except the ones
//! that are always-on (exercised implicitly by every scheduled frame) or
//! unreachable at this reference-world's granularity.

use stablehal_conformance::lin::runner::run_standard_suite;
use stablehal_conformance::lin::STANDARD_SUITE;

#[test]
fn reference_device_passes_standard_suite() {
    let report = run_standard_suite();
    assert!(
        report.all_pass(),
        "reference DUT failed some cases:\n{}",
        report.failure_text()
    );
    assert_eq!(report.passed(), STANDARD_SUITE.len());
}

#[test]
fn every_implemented_clause_is_probed_by_the_suite() {
    let report = run_standard_suite();
    let probed = report.probed_clauses(STANDARD_SUITE);
    // LIN-BREAK, LIN-BREAK-DELIM, LIN-SYNC, LIN-PID-PARITY are generated by
    // the reference master on every scheduled slot (conforming by
    // construction) rather than named in any single case's `probes` list —
    // this mirrors how the I2C suite treats I2C-BUS-FREE/I2C-BYTE-TIME.
    // LIN-ONE-RESPONSE requires two publishers driving the same frame slot
    // simultaneously, which this reference world's single-first-match
    // `add_slave` wiring cannot produce — it stays untested here, same
    // honesty pattern as MODBUS's `RTU-CHAR-OVERLAP` exception.
    let must_be_probed = [
        "LIN-CHECKSUM",
        "LIN-FRAME-MAXLEN",
        "LIN-INTERBYTE-MAX",
        "LIN-SLAVE-SILENCE",
    ];
    for clause in must_be_probed {
        assert!(
            probed.contains(&clause),
            "clause {clause} is not probed by any STANDARD_SUITE case"
        );
    }
}
