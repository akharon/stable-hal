//! LIN 2.2A timing (LIN Specification Package Revision 2.2A, §2.3.1 "Bit
//! rate and bit timing", §2.3.1.3 "Frame slot" / Table for maximum frame
//! length). All figures derive from the single nominal bit time `Tbit =
//! 1/baud`, per the spec's own definition — no separately-tuned constants.

use stablehal_contract::{Nanos, TimeBound};

#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct LinTiming {
    pub baud: u32,
    /// Nominal bit time (1/baud).
    pub bit_time: Nanos,
}

impl LinTiming {
    pub const fn new(baud: u32) -> Self {
        LinTiming {
            baud,
            bit_time: Nanos::from_nanos(1_000_000_000 / baud as u64),
        }
    }

    /// §2.3.1.3: the break field is >= 13 nominal bit times of dominant
    /// (low) level, generated by the master.
    pub fn break_min(&self) -> Nanos {
        self.bit_time.mul_ratio(13, 1)
    }

    /// §2.3.1.3: the break delimiter is >= 1 nominal bit time of recessive
    /// (high) level, separating the break from the sync byte.
    pub fn break_delimiter_min(&self) -> Nanos {
        self.bit_time
    }

    /// One UART-style byte on the LIN bus: 1 start + 8 data + 1 stop = 10
    /// nominal bit times (no parity bit on the wire byte itself — PID
    /// parity is encoded *within* the 8 data bits of the PID byte).
    pub fn byte_time(&self) -> Nanos {
        self.bit_time.mul_ratio(10, 1)
    }

    /// §2.3.1.3 Table 2: nominal header time = break(13) + break
    /// delimiter(1, treated as part of the inter-byte budget below) +
    /// sync byte(10) + PID byte(10) = 34 bit times is the commonly cited
    /// figure; we compute it compositionally instead of hardcoding 34 so a
    /// change to break/byte timing stays consistent.
    pub fn header_nominal(&self) -> Nanos {
        self.break_min() + self.bit_time + self.byte_time() + self.byte_time()
    }

    /// §2.3.1.3: nominal response time for `n_data` data bytes + 1 checksum
    /// byte = 10 * (n_data + 1) bit times.
    pub fn response_nominal(&self, n_data: u8) -> Nanos {
        self.bit_time.mul_ratio(10 * (n_data as u64 + 1), 1)
    }

    /// §2.3.1.3: T_frame_max = 1.4 * (T_header_nominal + T_response_nominal),
    /// truncated per the same integer-mul_ratio convention used elsewhere
    /// in StableHAL so every artifact computes the identical bound.
    pub fn frame_max(&self, n_data: u8) -> Nanos {
        (self.header_nominal() + self.response_nominal(n_data)).mul_ratio(7, 5)
    }

    /// §2.3.1.3: maximum inter-byte space *within* the response is bounded
    /// by the overall frame budget; a per-byte cap of the same 1.4x
    /// tolerance applied to one nominal byte time keeps a single stalled
    /// byte from silently consuming the whole frame budget.
    pub fn interbyte_max(&self) -> Nanos {
        self.byte_time().mul_ratio(7, 5)
    }

    /// Deployment contract term (not separately numbered in 2.2A, which
    /// leaves response-start latency to the frame budget as a whole):
    /// response must begin within the remaining frame budget after the
    /// header, i.e. inside `[0, response_nominal .. frame_max - header]`.
    pub fn response_start_envelope(&self, n_data: u8) -> TimeBound {
        TimeBound::new(Nanos::ZERO, self.frame_max(n_data) - self.header_nominal())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bit_time_at_19200() {
        let t = LinTiming::new(19_200);
        assert_eq!(t.bit_time, Nanos::from_nanos(52_083));
    }

    #[test]
    fn break_min_is_13_bits() {
        let t = LinTiming::new(19_200);
        assert_eq!(t.break_min(), t.bit_time.mul_ratio(13, 1));
    }

    #[test]
    fn frame_max_is_1_4x_nominal() {
        let t = LinTiming::new(19_200);
        let nominal = t.header_nominal() + t.response_nominal(8);
        assert_eq!(t.frame_max(8), nominal.mul_ratio(7, 5));
    }
}
